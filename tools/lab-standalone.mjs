/**
 * THE LAB, AS ONE FILE.
 *
 *   node tools/lab-standalone.mjs
 *
 * Builds lab.html through vite (so the kernel is compiled from the real
 * src/core sources, not retyped) and inlines the result into a single
 * portable HTML file with no external requests at all.
 *
 * Why it exists: the lab is most useful on whatever machine you happen
 * to be judging from, and that machine may have no node, no npm and no
 * checkout. One file opens anywhere.
 *
 * The output carries the baseline checksum for the site's seed and
 * compares it live against the constant tools/delta-verify.mjs prints.
 * If the standalone ever drifts from the shipped kernel, the footer of
 * the page itself says so - which is the point of generating it from
 * source rather than maintaining a copy.
 *
 * Output: captures/lab-standalone.html (captures/ is gitignored).
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, 'captures');

const vite = join(root, 'node_modules', 'vite', 'bin', 'vite.js');
if (!existsSync(vite)) {
  console.error('vite is not installed here. Run npm install first.');
  process.exit(1);
}

console.log('building lab.html from src/core ...');
execFileSync(process.execPath, [vite, 'build', '--config', 'tools/lab/vite.lab.config.ts'], {
  cwd: root,
  stdio: 'inherit'
});

const built = join(out, 'lab');
const html = readFileSync(join(built, 'lab.html'), 'utf8');
const js = readFileSync(join(built, 'lab.js'), 'utf8');

// the only external reference the built page has is its own script
const tag = /<script[^>]*src="\.\/lab\.js"[^>]*><\/script>/;
if (!tag.test(html)) {
  console.error('could not find the built script tag to inline. Did the build output change?');
  process.exit(1);
}

// a closing tag inside a string literal would end the script element early
const safe = js.replace(/<\/script/gi, '<\\/script');

// a FUNCTION replacement: a string one would interpret $' and $` in the
// minified code as "the rest of the document" and splice the page into
// its own script. This build happened not to contain them; the record
// build did.
const single = html.replace(
  tag,
  () =>
    `<script type="module">\n/* generated by tools/lab-standalone.mjs from src/core/Delta.ts,\n   src/core/causality.ts and tools/lab/main.ts. Do not edit here. */\n${safe}\n</script>`
);

if (!existsSync(out)) mkdirSync(out, { recursive: true });
const dest = join(out, 'lab-standalone.html');
writeFileSync(dest, single);

const kb = (single.length / 1024).toFixed(1);
console.log(`\nwrote ${dest}  (${kb} kB, no external requests)`);
if (/src\s*=\s*["']http/i.test(single) || /href\s*=\s*["']http/i.test(single)) {
  console.error('WARNING: the standalone references an external URL. It is meant to be self-contained.');
  process.exit(1);
}
console.log('verified: nothing in the file points outside itself.');
