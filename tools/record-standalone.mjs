/**
 * THE RECORD, AS ONE FILE.
 *
 *   node tools/record-standalone.mjs
 *
 * Builds record.html through vite from the real src, then inlines the
 * script, the stylesheet and both self-hosted fonts into a single HTML
 * file with no external requests - so the plate can be judged from a
 * machine with no node, no checkout and no server.
 *
 * Output: captures/record-standalone.html (captures/ is gitignored).
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, 'captures');

const vite = join(root, 'node_modules', 'vite', 'bin', 'vite.js');
if (!existsSync(vite)) {
  console.error('vite is not installed here. Run npm install first.');
  process.exit(1);
}

console.log('building record.html from src ...');
execFileSync(process.execPath, [vite, 'build', '--config', 'tools/plate/vite.plate.config.ts'], {
  cwd: root,
  stdio: 'inherit'
});

const built = join(out, 'record');
let html = readFileSync(join(built, 'record.html'), 'utf8');
const js = readFileSync(join(built, 'record.js'), 'utf8');
let css = readFileSync(join(built, 'record.css'), 'utf8');

// fonts: the site self-hosts them from public/fonts; embed them here
const fontUri = (file) =>
  `data:font/woff2;base64,${readFileSync(join(root, 'public', 'fonts', file)).toString('base64')}`;
// vite rewrites the absolute /fonts/ URL relative to base, so match the
// file name wherever the path put it
css = css
  .replace(/url\(['"]?[^'")]*archivo-var\.woff2['"]?\)/g, `url(${fontUri('archivo-var.woff2')})`)
  .replace(/url\(['"]?[^'")]*fragment-mono\.woff2['"]?\)/g, `url(${fontUri('fragment-mono.woff2')})`)
  // the fallback still is not shipped in the standalone; it is display:none anyway
  .replace(/url\(['"]?[^'")]*world\.jpg['"]?\)/g, 'none');
if (!/data:font\/woff2/.test(css)) {
  console.error('fonts were not embedded - the stylesheet no longer references them where expected.');
  process.exit(1);
}

const scriptTag = /<script[^>]*src="\.\/record\.js"[^>]*><\/script>/;
const linkTag = /<link[^>]*href="\.\/record\.css"[^>]*>/;
if (!scriptTag.test(html) || !linkTag.test(html)) {
  console.error('could not find the built script or stylesheet tag to inline.');
  process.exit(1);
}
// FUNCTION replacements, not strings. A string replacement interprets
// $' and $` as "the rest of the document" and minified code contains
// them, so the first version spliced the page's own HTML into its
// script and the browser reported "Unexpected token '<'".
const inlineScript =
  `<script type="module">\n/* generated by tools/record-standalone.mjs from src/plate. Do not edit here. */\n` +
  js.replace(/<\/script/gi, '<\\/script') +
  `\n</script>`;
html = html
  .replace(linkTag, () => `<style>\n${css}\n</style>`)
  .replace(scriptTag, () => inlineScript)
  // preload hints point at files this single page does not carry
  .replace(/<link rel="preload"[^>]*>\s*/g, '');

if (!existsSync(out)) mkdirSync(out, { recursive: true });
const dest = join(out, 'record-standalone.html');
writeFileSync(dest, html);
console.log(`\nwrote ${dest}  (${(html.length / 1024).toFixed(0)} kB, fonts embedded, no external requests)`);
if (/(src|href)\s*=\s*["']https?:/i.test(html)) {
  console.error('WARNING: the standalone references an external URL.');
  process.exit(1);
}
console.log('verified: nothing in the file points outside itself.');
